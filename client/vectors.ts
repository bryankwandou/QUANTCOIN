// Writes audit/test-vectors.txt: fixed inputs and the bytes this client produces for them.
// The on-chain program's own wots.rs (programs/qc-vault/tests/vectors.rs), the web app
// (app/test/vectors.test.ts) and the Android app (apps/native/test/vectors_test.dart)
// must reproduce every line exactly, so a signature made by any client verifies on chain.
// Run: npx tsx vectors.ts   (output is deterministic; no keys, no network)
import { writeFileSync } from "node:fs";
import { Keypair, PublicKey } from "@solana/web3.js";
import { TOKEN_2022_PROGRAM_ID, getAssociatedTokenAddressSync } from "@solana/spl-token";
import { digits, publicKeyHash, sign, spendDigest } from "./qc.ts";

const PROGRAM = new PublicKey("CiupyGrAtWomKW5rDWbaMEsm3Db8pY8NPECgL2FfACms");
const MINT = new PublicKey("AsEEaydVYMpghdNTrQoVZTAhJSewZT5xD9WE9hpA68W2");
const bytes = (n: number, f: (i: number) => number) => Buffer.from(Array.from({ length: n }, (_, i) => f(i) & 0xff));
const hex = (b: Uint8Array) => Buffer.from(b).toString("hex");
const key = (n: number) => new PublicKey(bytes(32, (i) => i * 13 + n));

const keys = [
  { master: bytes(32, (i) => i), seed: bytes(16, (i) => 255 - i) },
  { master: bytes(32, (i) => i * 37 + 11), seed: bytes(16, (i) => i * 7) },
  { master: Buffer.alloc(32), seed: Buffer.alloc(16, 0xff) },
];
// Edge digests: all digits 0 (longest checksum), all 255 (checksum 0), and a mixed one.
const digests = [Buffer.alloc(24), Buffer.alloc(24, 255), bytes(24, (i) => i * 11 + 3)];
const amounts = [0n, 1n, 12_345_678_900_000n, 2n ** 64n - 1n];

const out = [
  "# QuantCoin cross-implementation test vectors. Generated by client/vectors.ts. All values hex.",
  `# program ${hex(PROGRAM.toBytes())} (${PROGRAM.toBase58()})`,
  `# mint ${hex(MINT.toBytes())} (${MINT.toBase58()})`,
  "# pk <master> <seed> <pk_hash>",
  "# sig <master> <seed> <digest> <checksum digits d24 d25> <signature>",
  "# digest <program> <vault> <mint> <dest> <refund> <rent_to> <amount decimal> <digest>",
  "# pda <master> <seed> <owner_seed> <owner> <vault_pda> <bump>",
  "# ata <owner> <mint> <token_account>",
];
for (const k of keys) out.push(`pk ${hex(k.master)} ${hex(k.seed)} ${hex(publicKeyHash(k.master, k.seed))}`);
for (const k of keys) for (const d of digests) {
  const ds = digits(d);
  out.push(`sig ${hex(k.master)} ${hex(k.seed)} ${hex(d)} ${ds[24]} ${ds[25]} ${hex(sign(k.master, k.seed, d))}`);
}
const [v, m, d, r, t] = [1, 2, 3, 4, 5].map(key);
for (const a of amounts)
  out.push(`digest ${[PROGRAM, v, m, d, r, t].map((p) => hex(p.toBytes())).join(" ")} ${a} ${hex(spendDigest(PROGRAM, v, m, d, r, t, a))}`);
for (const [i, k] of keys.entries()) {
  const ownerSeed = bytes(32, (j) => j + 40 * i);
  const owner = Keypair.fromSeed(ownerSeed).publicKey;
  const [pda, bump] = PublicKey.findProgramAddressSync([Buffer.from("qcv"), publicKeyHash(k.master, k.seed), owner.toBuffer()], PROGRAM);
  out.push(`pda ${hex(k.master)} ${hex(k.seed)} ${hex(ownerSeed)} ${hex(owner.toBytes())} ${hex(pda.toBytes())} ${bump}`);
  const ata = getAssociatedTokenAddressSync(MINT, pda, true, TOKEN_2022_PROGRAM_ID);
  out.push(`ata ${hex(pda.toBytes())} ${hex(MINT.toBytes())} ${hex(ata.toBytes())}`);
}
writeFileSync(new URL("../audit/test-vectors.txt", import.meta.url), out.join("\n") + "\n");
console.log(`wrote ${out.length} lines to audit/test-vectors.txt`);
